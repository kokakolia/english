import { defineConfig } from "vite";
import react from "@vitejs/plugin-react";
import { VitePWA } from "vite-plugin-pwa";

function buildStamp(): string {
  const now = new Date();
  const pad = (value: number) => String(value).padStart(2, "0");
  return (
    `${now.getFullYear()}-${pad(now.getMonth() + 1)}-${pad(now.getDate())} ` +
    `${pad(now.getHours())}:${pad(now.getMinutes())}`
  );
}

export default defineConfig({
  // Время сборки видно в меню приложения. Без него вопрос «обновилось ли»
  // не имеет ответа: service worker отдаёт страницу из кэша, и отличить
  // свежую версию от старой на глаз нечем.
  define: { __BUILD_STAMP__: JSON.stringify(buildStamp()) },
  plugins: [
    react(),
    VitePWA({
      registerType: "autoUpdate",
      manifest: {
        name: "Английские коллокации",
        short_name: "Коллокации",
        description: "Интервальное повторение английских коллокаций",
        lang: "ru",
        start_url: "/",
        display: "standalone",
        // Цвет заставки при запуске. Совпадает с --paper: при несовпадении
        // окно на долю секунды вспыхивает белым, прежде чем показать бумагу.
        background_color: "#f3eedc",
        theme_color: "#f3eedc",
        // Без иконок Chrome не считает приложение устанавливаемым и просто не
        // показывает значок установки, ничего не сообщая. Нужен хотя бы один
        // PNG от 144 пикселей; кладём 192 и 512, как принято.
        icons: [
          { src: "/icon-192.png", sizes: "192x192", type: "image/png" },
          { src: "/icon-512.png", sizes: "512x512", type: "image/png" },
          {
            // Отдельный файл с широким полем: систему вправе обрезать иконку
            // до своей формы, и в общей у листа срезало бы кончики.
            src: "/icon-maskable-512.png",
            sizes: "512x512",
            type: "image/png",
            purpose: "maskable",
          },
        ],
      },
      workbox: {
        // Колода должна попасть в офлайн-кэш вместе с кодом: без неё
        // приложение откроется, но учить будет нечему.
        globPatterns: ["**/*.{js,css,html,json,svg,png,woff2}"],
        // Файл колоды крупнее стандартного порога; без этого он молча
        // выпадет из кэша, и офлайн сломается только у тех, кто ещё не
        // импортировал её в базу.
        maximumFileSizeToCacheInBytes: 8 * 1024 * 1024,
      },
    }),
  ],
  // Порты закреплены жёстко, и это не придирка к удобству.
  //
  // База IndexedDB привязана к источнику, то есть к паре «схема + порт». Если
  // порт занят, vite по умолчанию молча берёт соседний — приложение откроется,
  // но с пустой базой, как будто месяца занятий не было. `strictPort`
  // превращает эту тихую потерю в честный отказ запуститься.
  //
  // Порты **разные**, и это исправление настоящей поломки. Раньше оба режима
  // делили 5173. Стоило запустить `npm run dev`, и установленное приложение
  // переставало обновляться навсегда: dev-сервер не отдаёт service worker, на
  // запрос `/sw.js` он возвращает `index.html` с типом `text/html`, проверка
  // обновления отваливается, и старый кэш живёт вечно. Снаружи это выглядит
  // как «приложение не обновляется», без единого сообщения.
  //
  // Поэтому 5173 отдан собранному приложению и только ему. Разработка живёт на
  // 5174 — у неё своя база, и испортить настоящий прогресс она не может.
  server: { port: 5174, strictPort: true },
  preview: { port: 5173, strictPort: true },
});
